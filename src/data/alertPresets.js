export function getLocalizedAlert(alert, lang = 'en') {
  if (!alert) return null;
  const title = alert.localTitle?.[lang] || alert.localTitle?.en || alert.title;
  const triggerCondition = alert.localTriggerCondition?.[lang] || alert.localTriggerCondition?.en || alert.triggerCondition;
  const smsText = alert.smsText?.[lang] || alert.smsText?.en || alert.smsText?.te;
  const callScript = alert.callScript?.[lang] || alert.callScript?.en || alert.callScript?.te;
  const actionChecklist = alert.localActionChecklist?.[lang] || alert.localActionChecklist?.en || alert.actionChecklist;

  return {
    ...alert,
    title,
    triggerCondition,
    smsText,
    callScript,
    actionChecklist
  };
}
